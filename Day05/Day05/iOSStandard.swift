//# iOS Coding Standards
//
//* Follow **Swift API Design Guidelines** and use meaningful names.
//* Use **PascalCase** for types and **camelCase** for variables/functions.
//* Keep functions **small and focused** on one responsibility.
//* Use `private` and the most restrictive **access control** possible.
//* Avoid **force unwrapping (`!`)**.
//* Use `guard` for early exits and cleaner code.
//* Prefer `let` over `var` when values don't change.
//* Avoid **magic numbers**; use constants.
//* Follow **MVVM / Clean Architecture** and **SOLID principles**.
//* Use **Dependency Injection** instead of tightly coupled dependencies.
//* Keep Views focused on UI and ViewModels focused on state/business logic.
//* Use `async/await` for modern asynchronous programming.
//* Ensure UI updates happen on the **MainActor/Main Thread**.
//* Use `[weak self]` where required to avoid retain cycles.
//* Handle errors properly; don't silently ignore them.
//* Keep API/networking logic in a centralized network layer.
//* Write comments to explain **why**, not obvious code behavior.
//* Write clean, reusable, testable, and maintainable code.
